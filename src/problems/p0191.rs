//! LeetCode 第191题：位1的个数
//!
//! 题目链接：https://leetcode.cn/problems/number-of-1-bits/
//!
//! 编写一个函数，输入是一个无符号整数（以二进制串的形式），返回其二进制表达式中数字位数为 '1' 的个数（也被称为汉明重量）。
//!
//! 注意：在某些语言（如 Java）中，没有无符号整数类型。在这种情况下，输入和输出都将被指定为有符号整数类型，并且不应影响您的实现，因为无论整数是有符号的还是无符号的，其内部的二进制表示形式都是相同的。在 Java 中，编译器使用二进制补码表示有符号整数，因此下面的 示例 3 中输入表示有符号整数 -3。
//!
//! ## 示例
//!
//! 示例 1：
//! - 输入：n = 00000000000000000000000000001011
//! - 输出：3
//! - 解释：输入的二进制串 00000000000000000000000000001011 中，共有三位为 '1'。
//!
//! 示例 2：
//! - 输入：n = 00000000000000000000000010000000
//! - 输出：1
//! - 解释：输入的二进制串 00000000000000000000000010000000 中，共一位为 '1'。
//!
//! 示例 3：
//! - 输入：n = 11111111111111111111111111111101
//! - 输出：31
//! - 解释：输入的二进制串 11111111111111111111111111111101 中，共有 31 位为 '1'。
//!
//! ## 进阶
//!
//! 如果多次调用这个函数，你将如何优化你的算法？

use crate::Solution;

impl Solution {
    pub fn hamming_weight(n: i32) -> i32 {
        let mut n = n;
        let mut res = 0;
        loop {
            if n == 0 {
                return res;
            }
            if n % 2 == 1 {
                res += 1;
            }
            n = n / 2;
        }
    }
}

